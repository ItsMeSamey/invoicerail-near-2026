import { Worker } from 'near-workspaces';
import assert from 'node:assert/strict';
import { writeFile, mkdir, readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { extractEvents, reconcile, csv } from '../src/ledger.mjs';

const worker = await Worker.init({ network: 'sandbox' });
const gas = 100_000_000_000_000n;
const deposit = 10_000_000_000_000_000_000_000n;
const report = { network: 'local-sandbox', generatedAt: new Date().toISOString(), checks: [], steps: [], events: [] };
const check = (label, actual, expected) => { assert.deepEqual(actual, expected, label); report.checks.push(label); console.log(`PASS ${label}`); };
try {
  const root = worker.rootAccount;
  const merchant = await root.createSubAccount('merchant');
  const payer = await root.createSubAccount('customer');
  const other = await root.createSubAccount('other');
  const token = await root.createSubAccount('usd-demo');
  const rail = await root.createSubAccount('invoicerail');
  const tokenPath = 'contracts/target/wasm32-unknown-unknown/release/demo_token.wasm';
  const railPath = 'contracts/target/wasm32-unknown-unknown/release/invoicerail.wasm';
  await token.deploy(tokenPath);
  await rail.deploy(railPath);
  await token.call(token, 'new', { owner_id: payer.accountId, total_supply: '10000000000' });
  await rail.call(rail, 'new', { owner: merchant.accountId, token: token.accountId });
  report.contract = rail.accountId; report.token = token.accountId; report.merchant = merchant.accountId; report.payer = payer.accountId;
  report.wasmSha256 = {};
  for (const f of [railPath, tokenPath]) report.wasmSha256[f.split('/').at(-1)] = createHash('sha256').update(await readFile(f)).digest('hex');
  const register = account => root.call(token, 'storage_deposit', { account_id: account.accountId }, { attachedDeposit: deposit });
  await register(rail); await register(other);
  await payer.call(token, 'ft_transfer', { receiver_id: other.accountId, amount: '500000000' }, { attachedDeposit: 1n });
  const balance = account => token.view('ft_balance_of', { account_id: account.accountId });
  const state = id => rail.view('get_invoice', { id });
  const record = async (label, result) => {
    const finalized = await worker.provider.sendJsonRpc('tx', { tx_hash: result.result.transaction.hash, sender_account_id: result.result.transaction.signer_id, wait_until: 'FINAL' });
    assert.equal(finalized.final_execution_status, 'FINAL');
    report.events.push(...extractEvents(finalized, rail.accountId, token.accountId));
    const snapshot = reconcile(report.events);
    const chain = await rail.view('list_invoices', {});
    for (const i of chain) {
      const projected = snapshot.invoices.find(x => x.id === i.id);
      for (const field of ['due', 'received', 'withdrawn', 'pending', 'cancelled']) assert.deepEqual(projected[field], i[field], `Projection ${i.id}.${field}`);
    }
    report.steps.push({ label, transaction: finalized.transaction.hash, receiptFailures: result.receiptFailureMessages, eventCount: report.events.length, invoices: chain, balances: { payer: await balance(payer), merchant: await balance(merchant), contract: await balance(rail) }, raw: finalized });
    console.log(`STEP ${label}`);
    return result;
  };
  const create = async (id, due = '125000000', expires_ns = '9999999999999999999') => record(`Create ${id}`, await merchant.callRaw(rail, 'create_invoice', { id, payer: payer.accountId, due, expires_ns }, { attachedDeposit: deposit, gas }));
  const pay = async (id, amount, who = payer) => record(`Pay ${id}: ${amount} units`, await who.callRaw(token, 'ft_transfer_call', { receiver_id: rail.accountId, amount, msg: id }, { attachedDeposit: 1n, gas }));
  await create('INV-2026-001');
  const before = BigInt(await balance(payer));
  await pay('INV-2026-001', '40000000');
  check('Partial invoice receives exactly 40.00', (await state('INV-2026-001')).received, '40000000');
  await pay('INV-2026-001', '100000000');
  check('Overpayment capped at invoice amount', (await state('INV-2026-001')).received, '125000000');
  check('Actual token resolver returned 15.00 to payer', (before - BigInt(await balance(payer))).toString(), '125000000');
  await pay('INV-2026-001', '1000000');
  check('Already paid invoice returns the entire second payment', (before - BigInt(await balance(payer))).toString(), '125000000');
  await record('Merchant withdrawal fails before token registration', await merchant.callRaw(rail, 'withdraw', { id: 'INV-2026-001' }, { attachedDeposit: 1n, gas }));
  check('Failed withdrawal releases reservation', (await state('INV-2026-001')).pending, '0');
  check('Failed withdrawal leaves funds available', (await state('INV-2026-001')).withdrawn, '0');
  await register(merchant);
  await record('Registered merchant withdraws 125.00', await merchant.callRaw(rail, 'withdraw', { id: 'INV-2026-001' }, { attachedDeposit: 1n, gas }));
  check('Merchant actually receives tokens', await balance(merchant), '125000000');
  check('Contract token balance zero after withdrawal', await balance(rail), '0');
  const second = await merchant.callRaw(rail, 'withdraw', { id: 'INV-2026-001' }, { attachedDeposit: 1n, gas });
  check('Cannot withdraw twice', second.failed, true);
  await create('INV-2026-002', '80000000');
  const otherBefore = await balance(other);
  await pay('INV-2026-002', '10000000', other);
  check('Wrong payer gets full token refund', await balance(other), otherBefore);
  await pay('MISSING', '10000000');
  check('Unknown invoice leaves contract balance unchanged', await balance(rail), '0');
  await record('Cancel invoice 002', await merchant.callRaw(rail, 'cancel_invoice', { id: 'INV-2026-002' }, { gas }));
  await pay('INV-2026-002', '10000000');
  check('Cancelled invoice cannot collect', (await state('INV-2026-002')).received, '0');
  const spoof = await payer.callRaw(rail, 'ft_on_transfer', { sender_id: payer.accountId, amount: '1', msg: 'INV-2026-002' }, { gas });
  check('Only configured token may invoke receipt handler', spoof.failed, true);
  const callback = await payer.callRaw(rail, 'on_withdraw', { id: 'INV-2026-001' }, { gas });
  check('Withdrawal callback is private', callback.failed, true);
  const unauthorized = await payer.callRaw(rail, 'create_invoice', { id: 'NOPE', payer: payer.accountId, due: '1', expires_ns: '9999999999999999999' }, { attachedDeposit: deposit, gas });
  check('Invoice creation requires merchant', unauthorized.failed, true);
  const duplicate = await merchant.callRaw(rail, 'create_invoice', { id: 'INV-2026-001', payer: payer.accountId, due: '1', expires_ns: '9999999999999999999' }, { attachedDeposit: deposit, gas });
  check('Invoice IDs cannot be reused', duplicate.failed, true);
  await create('INV-2026-003', '30000000');
  await pay('INV-2026-003', '10000000');
  const overlapping = await merchant.batch(rail)
    .functionCall('withdraw', { id: 'INV-2026-003' }, { attachedDeposit: 1n, gas })
    .functionCall('withdraw', { id: 'INV-2026-003' }, { attachedDeposit: 1n, gas }).transact();
  check('Two withdrawals before callback cannot reserve the same funds', overlapping.failed, true);
  check('Pending reservation rejects overlap explicitly', overlapping.receiptFailureMessages.some(x => x.includes('already pending')), true);
  check('Failed batch rolls back reservation', (await state('INV-2026-003')).pending, '0');
  check('Failed batch leaves merchant balance unchanged', await balance(merchant), '125000000');
  const block = await worker.provider.block({ finality: 'final' });
  await create('INV-2026-004', '20000000', (BigInt(block.header.timestamp_nanosec) + 15_000_000_000n).toString());
  await worker.provider.fastForward(100);
  const beforeExpired = await balance(payer);
  await pay('INV-2026-004', '20000000');
  check('Expired invoice returns full payment through token resolver', await balance(payer), beforeExpired);
  check('Expired invoice has no accepted balance', (await state('INV-2026-004')).received, '0');
  const ledger = reconcile(report.events);
  check('Receipt replay is idempotent', reconcile([...report.events, ...report.events]), ledger);
  check('Ledger and token balance agree', ledger.invoices.reduce((n, i) => n + BigInt(i.available) + BigInt(i.pending), 0n).toString(), await balance(rail));
  report.ledger = ledger;
  report.passed = report.checks.length;
  await mkdir('artifacts', { recursive: true });
  await writeFile('artifacts/sandbox-report.json', JSON.stringify(report, null, 2) + '\n');
  await writeFile('artifacts/invoices.csv', csv(ledger));
  console.log(`\n${report.passed} checks passed. Report: artifacts/sandbox-report.json`);
} finally {
  await worker.tearDown();
}
